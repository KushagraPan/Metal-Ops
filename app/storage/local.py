"""Local-disk storage for uploaded report files.

The root is configurable with `STORAGE_DIR`. Keys are random and generated by
the storage layer, never by the client, so a filename cannot influence a path.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Iterable, BinaryIO
from uuid import uuid4

import app.env  # noqa: F401 - ensures .env is loaded before resolving STORAGE_DIR

from app.storage.base import (
    Storage,
    StorageError,
    StorageNotFound,
    StoredFile,
)

DEFAULT_STORAGE_DIR = "data/storage"


def storage_dir() -> Path:
    """Return the configured storage directory."""
    return Path(os.getenv("STORAGE_DIR") or DEFAULT_STORAGE_DIR).expanduser()


class LocalStorage:
    """Store report files as randomly named files below one root folder."""

    def __init__(self, root: str | Path | None = None) -> None:
        self.root = (
            Path(root).expanduser() if root is not None else storage_dir()
        )
        self.root.mkdir(parents=True, exist_ok=True)

    def save(self, chunks: Iterable[bytes]) -> StoredFile:
        self.root.mkdir(parents=True, exist_ok=True)
        key = f"{uuid4().hex}.pdf"
        path = self._path(key)
        size_bytes = 0
        try:
            with path.open("wb") as handle:
                for chunk in chunks:
                    if not chunk:
                        continue
                    handle.write(chunk)
                    size_bytes += len(chunk)
        except Exception:
            path.unlink(missing_ok=True)
            raise
        return StoredFile(key=key, size_bytes=size_bytes)

    def open(self, key: str) -> BinaryIO:
        path = self._path(key)
        try:
            return path.open("rb")
        except FileNotFoundError as error:
            raise StorageNotFound("report file not found") from error

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as error:
            raise StorageError("could not delete report file") from error

    def _path(self, key: str) -> Path:
        root = self.root.resolve()
        path = (root / key).resolve()
        if not path.is_relative_to(root):
            raise StorageError("invalid storage key")
        return path


def get_storage() -> Storage:
    """FastAPI dependency returning the configured storage backend."""
    return LocalStorage()
